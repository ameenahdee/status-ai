import { describe, it, beforeEach, afterEach, mock } from 'node:test'
import assert from 'node:assert/strict'
import { makeStorage, loadStore, releaseStorage, readPersisted, KEY } from './helpers/storage.mjs'
import { projectInput, reportInput, content, SECTION_KEYS } from './helpers/fixtures.mjs'
import { buildDemo } from '../src/demo.js'
import { SAMPLE_SCENARIO, samplePeriod } from '../src/samples.js'

const NOW = new Date(2026, 10, 8, 12, 0, 0)

describe('demo workspace data (buildDemo)', () => {
  const demo = buildDemo(NOW)

  it('provides ten projects and thirteen reports', () => {
    assert.equal(demo.projects.length, 10)
    assert.equal(demo.reports.length, 13)
  })

  it('uses unique, stable ids that do not change between builds', () => {
    const ids = [...demo.projects, ...demo.reports].map((x) => x.id)
    assert.equal(new Set(ids).size, ids.length)
    assert.deepEqual(buildDemo(new Date(2027, 0, 1)).projects.map((p) => p.id), demo.projects.map((p) => p.id))
    assert.deepEqual(buildDemo(new Date(2027, 0, 1)).reports.map((r) => r.id), demo.reports.map((r) => r.id))
  })

  it('flags every record as demo, and no report as a sample copy or live AI', () => {
    assert.ok(demo.projects.every((p) => p.demo === true))
    assert.ok(demo.reports.every((r) => r.demo === true && r.source === 'demo' && !r.sampleCopy))
  })

  it('gives every project a meaningful description within the 500-character limit', () => {
    for (const p of demo.projects) {
      assert.ok(p.description.length >= 40 && p.description.length <= 500, p.name)
    }
  })

  it('uses a realistic mix of all four statuses, not just On Track', () => {
    const statuses = new Set(demo.projects.map((p) => p.status))
    assert.deepEqual([...statuses].sort(), ['At Risk', 'Blocked', 'Off Track', 'On Track'])
  })

  it('links every report to a real project', () => {
    const ids = new Set(demo.projects.map((p) => p.id))
    assert.ok(demo.reports.every((r) => ids.has(r.projectId)))
  })

  it('gives every report exactly the seven sections, each with content', () => {
    for (const r of demo.reports) {
      assert.deepEqual(Object.keys(r.content).filter((k) => k !== 'title').sort(), [...SECTION_KEYS].sort(), r.id)
      assert.ok(r.content.executiveSummary.length > 0, r.id)
      for (const k of SECTION_KEYS.slice(1)) assert.ok(r.content[k].length > 0, `${r.id}.${k}`)
    }
  })

  it('keeps each original update, a valid reporting period, and a separate generation date', () => {
    for (const r of demo.reports) {
      assert.ok(r.originalUpdate.length > 20, r.id)
      assert.match(r.periodStart, /^\d{4}-\d{2}-\d{2}$/)
      assert.match(r.periodEnd, /^\d{4}-\d{2}-\d{2}$/)
      assert.ok(r.periodEnd >= r.periodStart, r.id)
      assert.ok(new Date(r.savedAt) <= NOW, `${r.id} is dated in the future`)
      assert.equal(r.generatedAt, null, `${r.id}: demo reports were never generated by the AI`)
    }
  })

  it('starts each project before its first report period', () => {
    const start = Object.fromEntries(demo.projects.map((p) => [p.id, p.startDate]))
    assert.ok(demo.reports.every((r) => start[r.projectId] <= r.periodStart))
  })

  it('ties a project\'s status to its latest report and says so', () => {
    for (const p of demo.projects) {
      const reps = demo.reports.filter((r) => r.projectId === p.id).sort((a, b) => b.savedAt.localeCompare(a.savedAt))
      if (reps.length) {
        assert.equal(p.status, reps[0].projectStatusAtReport, p.name)
        assert.deepEqual([p.statusSource.type, p.statusSource.reportId], ['report', reps[0].id])
      } else {
        assert.equal(p.statusSource.type, 'manual') // a project without reports has a manual status
      }
    }
  })

  it('includes at least one project with no reports yet', () => {
    assert.ok(demo.projects.some((p) => !demo.reports.some((r) => r.projectId === p.id)))
  })
})

describe('demo workspace actions', () => {
  let storage, store
  beforeEach(async () => {
    storage = makeStorage()
    store = await loadStore(storage)
  })
  afterEach(releaseStorage)
  const persisted = () => readPersisted(storage)

  describe('loadDemo', () => {
    it('adds the demo projects and reports and persists them', () => {
      const r = store.actions.loadDemo()
      assert.deepEqual(r, { addedProjects: 10, addedReports: 13 })
      assert.equal(persisted().projects.length, 10)
      assert.equal(persisted().reports.length, 13)
      assert.equal(store.hasDemo(persisted()), true)
    })

    it('does not create duplicates when loaded again', () => {
      store.actions.loadDemo()
      const second = store.actions.loadDemo()
      assert.deepEqual(second, { addedProjects: 0, addedReports: 0 })
      assert.equal(persisted().projects.length, 10)
      assert.equal(persisted().reports.length, 13)
    })

    it('leaves existing user projects and reports untouched', () => {
      const p = store.actions.createProject(projectInput({ name: 'Mine' }))
      const r = store.actions.addReport(reportInput(p.id))
      const before = JSON.stringify([persisted().projects[0], persisted().reports[0]])
      store.actions.loadDemo()
      const s = persisted()
      assert.equal(JSON.stringify([s.projects.find((x) => x.id === p.id), s.reports.find((x) => x.id === r.id)]), before)
      assert.equal(s.projects.length, 11)
    })

    it('restores a demo report the visitor deleted (documents current behaviour)', () => {
      store.actions.loadDemo()
      store.actions.deleteReport('demo-r-01-1')
      assert.equal(persisted().reports.length, 12)
      assert.deepEqual(store.actions.loadDemo(), { addedProjects: 0, addedReports: 1 })
    })
  })

  describe('Save a Copy (saveSampleCopy)', () => {
    beforeEach(() => {
      store.actions.loadDemo()
      mock.timers.enable({ apis: ['Date'], now: new Date('2026-11-10T09:00:00.000Z') })
    })
    afterEach(() => mock.timers.reset())

    const source = () => persisted().reports.find((r) => r.id === 'demo-r-02-2')
    const copyOf = (srcReport, over = {}) => ({
      projectId: srcReport.projectId,
      content: srcReport.content,
      originalUpdate: srcReport.originalUpdate,
      periodStart: srcReport.periodStart,
      periodEnd: srcReport.periodEnd,
      copiedFrom: srcReport.id,
      projectStatusAtReport: srcReport.projectStatusAtReport,
      ...over,
    })

    it('creates a separate saved report and does not save anything else', () => {
      const before = persisted().reports.length
      const copy = store.actions.saveSampleCopy(copyOf(source()))
      assert.notEqual(copy.id, 'demo-r-02-2')
      assert.equal(persisted().reports.length, before + 1)
      assert.deepEqual(persisted().reports.find((r) => r.id === copy.id), copy)
    })

    it('is identified as a sample copy: not live AI, not a plain demo report', () => {
      const copy = store.actions.saveSampleCopy(copyOf(source()))
      assert.equal(copy.source, 'sample-copy')
      assert.equal(copy.sampleCopy, true)
      assert.equal(copy.demo, true)
      assert.equal(copy.copiedFrom, 'demo-r-02-2')
    })

    it('keeps every edit the visitor made before saving', () => {
      const edited = content({ title: 'My edited title', executiveSummary: 'My own words.', risks: ['Edited risk'] })
      const copy = store.actions.saveSampleCopy(copyOf(source(), { content: edited }))
      assert.equal(copy.content.executiveSummary, 'My own words.')
      assert.deepEqual(copy.content.risks, ['Edited risk'])
      assert.equal(copy.title, 'My edited title')
    })

    it('leaves the original report exactly as it was', () => {
      const before = JSON.stringify(source())
      const edited = content({ executiveSummary: 'Changed in the copy only.' })
      store.actions.saveSampleCopy(copyOf(source(), { content: edited }))
      assert.equal(JSON.stringify(source()), before)
    })

    it('is a deep copy: changing the object that was passed in later does not change the saved copy', () => {
      const edited = content({ completedActivities: ['one', 'two'] })
      const copy = store.actions.saveSampleCopy(copyOf(source(), { content: edited }))
      edited.completedActivities.push('SNEAKED IN')
      edited.executiveSummary = 'MUTATED'
      // Force another save: if the store were holding the same object, this would write the change out.
      store.actions.deleteReport('__no-such-report__')
      const saved = persisted().reports.find((r) => r.id === copy.id)
      assert.deepEqual(saved.content.completedActivities, ['one', 'two'])
      assert.equal(saved.content.executiveSummary, 'Summary text.')
    })

    it('keeps the original update, reporting period and a separate save date', () => {
      const copy = store.actions.saveSampleCopy(copyOf(source()))
      assert.equal(copy.originalUpdate, source().originalUpdate)
      assert.equal(copy.periodStart, source().periodStart)
      assert.equal(copy.periodEnd, source().periodEnd)
      assert.equal(copy.savedAt, '2026-11-10T09:00:00.000Z') // when the copy was saved
      assert.equal(copy.generatedAt, null) // a sample copy was never generated by the AI
    })

    it('appears in the chosen project\'s history alongside its existing reports', () => {
      const copy = store.actions.saveSampleCopy(copyOf(source()))
      const history = store.reportsFor(persisted(), source().projectId).map((r) => r.id)
      assert.ok(history.includes(copy.id))
      assert.ok(history.includes('demo-r-02-1') && history.includes('demo-r-02-2'))
      assert.equal(history.length, 3)
    })

    it('appears in the Reports library but not in other projects\' history', () => {
      const copy = store.actions.saveSampleCopy(copyOf(source()))
      assert.ok(persisted().reports.some((r) => r.id === copy.id))
      assert.ok(!store.reportsFor(persisted(), 'demo-p-01').some((r) => r.id === copy.id))
    })

    it('can be saved into a different demo project than the original\'s', () => {
      const copy = store.actions.saveSampleCopy(copyOf(source(), { projectId: 'demo-p-04' }))
      assert.equal(copy.projectId, 'demo-p-04')
      assert.ok(store.reportsFor(persisted(), 'demo-p-04').some((r) => r.id === copy.id))
    })

    it('allows saving several separate copies, each with its own id', () => {
      const a = store.actions.saveSampleCopy(copyOf(source()))
      const b = store.actions.saveSampleCopy(copyOf(source()))
      assert.notEqual(a.id, b.id)
      assert.equal(persisted().reports.filter((r) => r.sampleCopy).length, 2)
    })

    it('does not change the project\'s status or any other project', () => {
      const before = JSON.stringify(persisted().projects)
      store.actions.saveSampleCopy(copyOf(source()))
      assert.equal(JSON.stringify(persisted().projects), before)
    })

    it('survives a page refresh', async () => {
      const copy = store.actions.saveSampleCopy(copyOf(source()))
      const reloaded = await loadStore(storage) // a fresh load of the app over the same storage
      assert.ok(reloaded && persisted().reports.some((r) => r.id === copy.id))
      reloaded.actions.createProject(projectInput({ name: 'After refresh' })) // writes using the loaded state
      assert.ok(persisted().reports.some((r) => r.id === copy.id), 'copy was lost after a refresh and a new write')
    })
  })

  describe('resetDemo', () => {
    beforeEach(() => store.actions.loadDemo())

    it('removes every demo project and report, returning how many', () => {
      const r = store.actions.resetDemo()
      assert.deepEqual(r, { removedProjects: 10, removedReports: 13, keptProjects: 0 })
      assert.deepEqual(persisted().projects, [])
      assert.deepEqual(persisted().reports, [])
      assert.equal(store.hasDemo(persisted()), false)
    })

    it('also removes saved sample copies', () => {
      const src = persisted().reports.find((r) => r.id === 'demo-r-01-2')
      store.actions.saveSampleCopy({ projectId: src.projectId, content: src.content, originalUpdate: src.originalUpdate, periodStart: src.periodStart, periodEnd: src.periodEnd, copiedFrom: src.id })
      store.actions.saveSampleCopy({ projectId: 'demo-p-03', content: content(), originalUpdate: 'x', periodStart: '2026-11-01', periodEnd: '2026-11-07', copiedFrom: 'sample:customer-portal' })
      const r = store.actions.resetDemo()
      assert.equal(r.removedReports, 15)
      assert.equal(persisted().reports.filter((x) => x.sampleCopy).length, 0)
    })

    it('never touches projects or reports the user created', () => {
      const mine = store.actions.createProject(projectInput({ name: 'Mine' }))
      const myReport = store.actions.addReport(reportInput(mine.id))
      const before = JSON.stringify([persisted().projects.find((p) => p.id === mine.id), persisted().reports.find((r) => r.id === myReport.id)])
      store.actions.resetDemo()
      const s = persisted()
      assert.equal(s.projects.length, 1)
      assert.equal(s.reports.length, 1)
      assert.equal(JSON.stringify([s.projects[0], s.reports[0]]), before)
    })

    it('keeps a demo project that holds a report the user saved, as a normal project', () => {
      const mine = store.actions.addReport(reportInput('demo-p-04', { originalUpdate: 'MY OWN NOTES' }))
      const r = store.actions.resetDemo()
      const s = persisted()
      assert.equal(r.keptProjects, 1)
      assert.equal(r.removedProjects, 9)
      assert.equal(s.projects.length, 1)
      assert.equal(s.projects[0].id, 'demo-p-04')
      assert.equal(s.projects[0].demo, false)
      assert.deepEqual(s.reports.map((x) => x.id), [mine.id])
      assert.equal(s.reports[0].originalUpdate, 'MY OWN NOTES')
    })

    it('only removes demo records from the app\'s own key, never other stored data', () => {
      storage.setItem('some-other-app-key', 'keep me')
      store.actions.resetDemo()
      assert.equal(storage.getItem('some-other-app-key'), 'keep me')
      assert.ok(storage.getItem(KEY))
    })

    it('does nothing harmful on a workspace with no demo data', async () => {
      const fresh = await loadStore(makeStorage())
      assert.deepEqual(fresh.actions.resetDemo(), { removedProjects: 0, removedReports: 0, keptProjects: 0 })
    })

    it('can be followed by loading the demo again', () => {
      store.actions.resetDemo()
      assert.deepEqual(store.actions.loadDemo(), { addedProjects: 10, addedReports: 13 })
    })
  })
})

describe('prepared sample scenario', () => {
  it('has a fictional update and a report with exactly the seven sections', () => {
    assert.ok(SAMPLE_SCENARIO.update.length > 50)
    assert.deepEqual(Object.keys(SAMPLE_SCENARIO.report).filter((k) => k !== 'title').sort(), [...SECTION_KEYS].sort())
    for (const k of SECTION_KEYS.slice(1)) assert.ok(SAMPLE_SCENARIO.report[k].length > 0, k)
  })

  it('agrees with its own update on the key facts, and invents none of its own', () => {
    const r = JSON.stringify(SAMPLE_SCENARIO.report)
    for (const fact of ['60%', '15th']) assert.ok(SAMPLE_SCENARIO.update.includes(fact) && r.includes(fact), fact)
    assert.ok(/2 weeks/.test(SAMPLE_SCENARIO.update) && /two weeks/.test(r))
    assert.ok(/3 flaky/.test(SAMPLE_SCENARIO.update) && /Three flaky/.test(r))
    assert.ok(!/QA cycle|investigation/i.test(r), 'the sample report must not invent activity')
  })

  it('marks suggestions that the update does not state with "Suggested:"', () => {
    assert.ok(JSON.stringify(SAMPLE_SCENARIO.report).includes('Suggested:'))
  })

  it('points at a demo project that actually exists', () => {
    assert.ok(buildDemo(NOW).projects.some((p) => p.id === SAMPLE_SCENARIO.defaultDemoProjectId))
  })

  it('suggests a valid seven-day reporting period ending yesterday', () => {
    assert.deepEqual(samplePeriod(new Date(2026, 10, 8)), { periodStart: '2026-11-01', periodEnd: '2026-11-07' })
  })

  it('writes nothing to storage by itself: samples are previews until a copy is explicitly saved', async () => {
    const storage = makeStorage()
    await loadStore(storage)
    samplePeriod()
    structuredClone(SAMPLE_SCENARIO.report)
    assert.equal(storage.getItem(KEY), null)
    releaseStorage()
  })
})
